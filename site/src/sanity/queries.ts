// Generated by `npm run typegen` in studio-dagenhamupdates/ (schema extract +
// sanity typegen generate) — re-run it after editing a query below or the
// schema. Never hand-edit this file. Only imported for the one type below
// (PostRow) — sanityFetch's own (stega-branded) inference governs everywhere
// else, since forcing these plain generated types onto its branded return
// is what conflicts; see the comment on PostRow.
import type { LATEST_POSTS_QUERY_RESULT } from "../../sanity.types";

// This module is the one seam the rest of the app depends on for content —
// every function below returns the same shape whether Sanity is configured
// or not. Without NEXT_PUBLIC_SANITY_PROJECT_ID set, everything falls back
// to the sample data in src/lib/content/*.ts (unchanged, still the same
// files the design canvas's copy came from), so the site keeps working
// end to end before a CMS project exists. See site/README.md.
//
// Reads go through `sanityFetch` (src/sanity/live.ts's defineLive) rather
// than a plain client.fetch — that's what makes the Live Content API and
// Visual Editing work. Fields used as identifiers (slug, category — routing,
// lookups, comparisons) are run through `stegaClean` at this mapping layer:
// Visual Editing can embed invisible characters in any string field, and the
// "golden rule" is clean anything used for logic, leave anything only ever
// *displayed* (title, standfirst, body...) alone so click-to-edit still
// works on it. See the sanity-best-practices skill's visual-editing.md.
//
// Queries are each a fully inline, standalone `defineQuery(...)` (no shared
// fragment interpolation) so `npm run typegen` (studio-dagenhamupdates/) can
// statically extract and type every one of them into site/sanity.types.ts —
// see the TypeGen docs' "Supported Query Formats" for why a composed/
// interpolated query string isn't reliably extractable.

// ---- Queries ----------------------------------------------------------

const CATEGORIES_QUERY = defineQuery(
  `*[_type == "category"] | order(name asc){"slug": slug.current, name, description}`
);

const CATEGORY_BY_SLUG_QUERY = defineQuery(
  `*[_type == "category" && slug.current == $slug][0]{"slug": slug.current, name, description}`
);

const LATEST_POSTS_QUERY = defineQuery(`
  *[_type == "post"] | order(publishedAt desc) {
    "slug": slug.current, title, "category": category->slug.current, publishedAt, updatedAt,
    standfirst, developing, severity, sourceAttribution, featuredImage{asset, hotspot, alt, credit}
  }
`);

const POSTS_BY_CATEGORY_QUERY = defineQuery(`
  *[_type == "post" && category->slug.current == $slug] | order(publishedAt desc) {
    "slug": slug.current, title, "category": category->slug.current, publishedAt, updatedAt,
    standfirst, developing, severity, sourceAttribution, featuredImage{asset, hotspot, alt, credit}
  }
`);

const FEATURED_POST_QUERY = defineQuery(`
  *[_type == "post" && featured == true] | order(publishedAt desc) [0] {
    "slug": slug.current, title, "category": category->slug.current, publishedAt, updatedAt,
    standfirst, developing, severity, sourceAttribution, featuredImage{asset, hotspot, alt, credit}
  }
`);

const BREAKING_POST_QUERY = defineQuery(`
  *[_type == "post" && breaking == true] | order(publishedAt desc) [0] {
    "slug": slug.current, title, "category": category->slug.current, publishedAt, updatedAt,
    standfirst, developing, severity, sourceAttribution, featuredImage{asset, hotspot, alt, credit}
  }
`);

const SPOTLIGHT_POSTS_QUERY = defineQuery(`
  *[_type == "post" && spotlight == true] | order(publishedAt desc) [0...3] {
    "slug": slug.current, title, "category": category->slug.current, publishedAt, updatedAt,
    standfirst, developing, severity, sourceAttribution, featuredImage{asset, hotspot, alt, credit}
  }
`);

const ALL_POST_SLUGS_QUERY = defineQuery(`*[_type == "post"]{"slug": slug.current}`);

const POST_BY_SLUG_QUERY = defineQuery(`
  *[_type == "post" && slug.current == $slug][0]{
    "slug": slug.current,
    title,
    "category": category->slug.current,
    publishedAt,
    updatedAt,
    standfirst,
    developing,
    severity,
    body,
    sourceAttribution,
    sourcesLog,
    metaTitle,
    metaDescription,
    featuredImage{asset, hotspot, alt, credit},
    "relatedPosts": relatedPosts[]->{
      "slug": slug.current, title, "category": category->slug.current, publishedAt, updatedAt,
      standfirst, developing, severity, sourceAttribution, featuredImage{asset, hotspot, alt, credit}
    }
  }
`);

const UPCOMING_EVENTS_QUERY = defineQuery(
  `*[_type == "event" && date >= now()] | order(date asc) [0...5]{title, date, location, detail, link}`
);

const TRAVEL_ALERTS_QUERY = defineQuery(`
  *[_type == "travelAlert" && active == true] | order(updatedAt desc){
    severity, title, detail, "relatedPostSlug": relatedPost->slug.current
  }
`);

// ---- Row -> view-model mapping -----------------------------------------
//
// The generated *_QUERY_RESULT types are the source of truth for what a row
// actually contains (see sanity.types.ts); everything below just reshapes
// that into the app's view types (PostSummary/PostDetail/etc — src/sanity/types.ts),
// which is also what the local fallback data maps into. `category` comes
// back as a plain `string` from the dereference (TypeGen can't know it's
// always one of the five slugs), so it's asserted to CategorySlug at this
// one boundary rather than widening the view types everywhere downstream.
//
// `severity` is widened to plain `string | null` here (rather than the
// generated literal union) because sanityFetch's return is stega-branded:
// a branded literal like `StegaString<"clear">` isn't assignable to the
// literal type `"clear"` until cleaned — see stegaClean() below. Every other
// field is a plain (non-literal) string, which a stega brand *is*
// structurally assignable to, so only this one field needs the widening.
type PostRow = Omit<LATEST_POSTS_QUERY_RESULT[number], "severity"> & { severity: string | null };

function mapImage(
  image: PostRow["featuredImage"]
): { imageUrl?: string; imageAlt?: string; imageCredit?: string } {
  if (!image?.asset) return {};
  const url = urlForImage(image as SanityImageSource)?.width(1200).url();
  return { imageUrl: url, imageAlt: image.alt ?? undefined, imageCredit: image.credit ?? undefined };
}

function cleanSeverity(value: string | null | undefined): Severity | undefined {
  return value ? (stegaClean(value) as Severity) : undefined;
}

function mapPostSummary(raw: PostRow): PostSummary {
  return {
    slug: stegaClean(raw.slug),
    title: raw.title,
    category: stegaClean(raw.category) as CategorySlug,
    publishedAt: raw.publishedAt,
    updatedAt: raw.updatedAt ?? undefined,
    standfirst: raw.standfirst,
    developing: Boolean(raw.developing),
    severity: cleanSeverity(raw.severity),
    sourceAttribution: raw.sourceAttribution ?? undefined,
    ...mapImage(raw.featuredImage),
  };
}

// ---- Categories -----------------------------------------------------------

export async function getCategories(): Promise<CategoryView[]> {
  if (!isSanityConfigured) return fallbackCategories.categories;
  const { data: rows } = await sanityFetch({ query: CATEGORIES_QUERY });
  return rows.map((row) => ({ ...row, slug: stegaClean(row.slug) as CategorySlug }));
}

export async function getCategory(
  slug: string,
  options?: { stega?: boolean }
): Promise<CategoryView | undefined> {
  if (!isSanityConfigured) return fallbackCategories.getCategory(slug);
  const { data: row } = await sanityFetch({
    query: CATEGORY_BY_SLUG_QUERY,
    params: { slug },
    stega: options?.stega,
  });
  return row ? { ...row, slug: stegaClean(row.slug) as CategorySlug } : undefined;
}

// ---- Post summaries (feed, category, homepage rail) ------------------------

export async function getLatestPosts(limit?: number): Promise<PostSummary[]> {
  if (!isSanityConfigured) {
    return fallbackPosts.getLatestPosts(limit).map(fallbackToSummary);
  }
  const { data: rows } = await sanityFetch({ query: LATEST_POSTS_QUERY });
  const summaries = rows.map(mapPostSummary);
  return typeof limit === "number" ? summaries.slice(0, limit) : summaries;
}

export async function getPostsByCategory(slug: CategorySlug): Promise<PostSummary[]> {
  if (!isSanityConfigured) {
    return fallbackPosts.getPostsByCategory(slug).map(fallbackToSummary);
  }
  const { data: rows } = await sanityFetch({ query: POSTS_BY_CATEGORY_QUERY, params: { slug } });
  return rows.map(mapPostSummary);
}

export async function getFeaturedPost(): Promise<PostSummary | undefined> {
  if (!isSanityConfigured) return fallbackToSummary(fallbackPosts.getFeaturedPost());
  const { data: row } = await sanityFetch({ query: FEATURED_POST_QUERY });
  return row ? mapPostSummary(row) : undefined;
}

export async function getBreakingPost(): Promise<PostSummary | undefined> {
  if (!isSanityConfigured) {
    const post = fallbackPosts.getBreakingPost();
    return post ? fallbackToSummary(post) : undefined;
  }
  const { data: row } = await sanityFetch({ query: BREAKING_POST_QUERY });
  return row ? mapPostSummary(row) : undefined;
}

// The 3 posts the design canvas hand-picked for the sample content (kept as
// the local fallback so that view is unchanged); in Sanity, editors control
// this with the post schema's `spotlight` boolean instead of a fixed list.
const FALLBACK_SPOTLIGHT_SLUGS = [
  "litter-pick-group-hundredth-saturday",
  "local-sixth-form-engineering-course",
  "family-bakery-reopens",
];

export async function getSpotlightPosts(): Promise<PostSummary[]> {
  if (!isSanityConfigured) {
    return FALLBACK_SPOTLIGHT_SLUGS.map((slug) => fallbackPosts.getPost(slug))
      .filter((p): p is fallbackPosts.Post => Boolean(p))
      .map(fallbackToSummary);
  }
  const { data: rows } = await sanityFetch({ query: SPOTLIGHT_POSTS_QUERY });
  return rows.map(mapPostSummary);
}

export async function getAllPostSlugs(): Promise<string[]> {
  if (!isSanityConfigured) return fallbackPosts.posts.map((p) => p.slug);
  // Static params: published only, no stega — see nextjs.md §4.C.
  const { data: rows } = await sanityFetch({
    query: ALL_POST_SLUGS_QUERY,
    perspective: "published",
    stega: false,
  });
  return rows.map((r) => r.slug);
}

// ---- Post detail (article page) --------------------------------------------

export async function getPost(
  slug: string,
  options?: { stega?: boolean }
): Promise<PostDetail | undefined> {
  if (!isSanityConfigured) {
    const post = fallbackPosts.getPost(slug);
    if (!post) return undefined;
    return {
      ...fallbackToSummary(post),
      updatedAt: post.updatedAt,
      body: paragraphsToPortableText(post.body),
      sourceAttribution: post.sourceAttribution,
      sourcesLog: post.sourcesLog,
      relatedPosts: fallbackPosts.getRelatedPosts(post).map(fallbackToSummary),
    };
  }

  const { data: raw } = await sanityFetch({
    query: POST_BY_SLUG_QUERY,
    params: { slug },
    stega: options?.stega,
  });
  if (!raw) return undefined;
  const { featuredImage, relatedPosts, sourcesLog, metaTitle, metaDescription, ...rest } = raw;
  return {
    ...rest,
    slug: stegaClean(rest.slug),
    category: stegaClean(rest.category) as CategorySlug,
    updatedAt: rest.updatedAt ?? undefined,
    developing: Boolean(rest.developing),
    severity: cleanSeverity(rest.severity),
    ...mapImage(featuredImage),
    sourcesLog: (sourcesLog ?? []).map((entry) => ({ at: entry.at ?? "", note: entry.note ?? "" })),
    metaTitle: metaTitle ?? undefined,
    metaDescription: metaDescription ?? undefined,
    relatedPosts: (relatedPosts ?? []).map(mapPostSummary),
  };
}

function fallbackToSummary(post: fallbackPosts.Post): PostSummary {
  return {
    slug: post.slug,
    title: post.title,
    category: post.category,
    publishedAt: post.publishedAt,
    updatedAt: post.updatedAt,
    standfirst: post.standfirst,
    developing: post.developing,
    severity: post.severity,
    sourceAttribution: post.sourceAttribution,
  };
}

// ---- Homepage extras: events, travel alerts --------------------------------

export async function getUpcomingEvents(): Promise<CalendarEvent[]> {
  if (!isSanityConfigured) return fallbackExtras.upcomingEvents;
  const { data: rows } = await sanityFetch({ query: UPCOMING_EVENTS_QUERY });
  return rows.map((row) => ({
    title: row.title,
    date: row.date,
    location: row.location ?? undefined,
    detail: row.detail ?? undefined,
    link: row.link ?? undefined,
  }));
}

export async function getTravelAlerts(): Promise<TravelAlertView[]> {
  if (!isSanityConfigured) {
    return sortBySeverity(
      fallbackExtras.travelAlerts.map((a) => ({
        severity: a.severity,
        title: a.title,
        detail: a.detail,
        relatedPostSlug: a.articleSlug,
      }))
    );
  }
  const { data: rows } = await sanityFetch({ query: TRAVEL_ALERTS_QUERY });
  return sortBySeverity(
    rows.map((row) => ({
      severity: cleanSeverity(row.severity) ?? "clear",
      title: row.title,
      detail: row.detail ?? undefined,
      relatedPostSlug: row.relatedPostSlug ? stegaClean(row.relatedPostSlug) : undefined,
    }))
  );
}

// Most urgent first, editing time is a tiebreaker only — GROQ's `order()`
// can't express a custom enum priority, and sorting by updatedAt alone put
// the closed-road alert last just because it happened to be edited first.
const severityRank: Record<Severity, number> = { severe: 0, minor: 1, clear: 2 };
function sortBySeverity(alerts: TravelAlertView[]): TravelAlertView[] {
  return [...alerts].sort((a, b) => severityRank[a.severity] - severityRank[b.severity]);
}
