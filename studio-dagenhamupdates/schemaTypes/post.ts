import { defineField, defineType } from "sanity";

export const post = defineType({
  name: "post",
  title: "Post",
  type: "document",
  groups: [
    { name: "content", title: "Content", default: true },
    { name: "meta", title: "Meta & trust" },
    { name: "seo", title: "SEO" },
  ],
  fields: [
    defineField({
      group: "content",
      name: "title",
      title: "Title",
      type: "string",
      validation: (rule) => rule.required(),
    }),
    defineField({
      group: "content",
      name: "slug",
      title: "Slug",
      type: "slug",
      options: { source: "title", maxLength: 96 },
      validation: (rule) => rule.required(),
    }),
    defineField({
      group: "content",
      name: "category",
      title: "Category",
      type: "reference",
      to: [{ type: "category" }],
      validation: (rule) => rule.required(),
    }),
    defineField({
      group: "content",
      name: "standfirst",
      title: "Standfirst",
      description: "The short summary shown on cards and under the headline.",
      type: "text",
      rows: 2,
      validation: (rule) => rule.required().max(240),
    }),
    defineField({
      group: "content",
      name: "featuredImage",
      title: "Featured image",
      type: "image",
      options: { hotspot: true },
      fields: [
        defineField({
          name: "alt",
          title: "Alt text",
          type: "string",
          description: "Required whenever an image is set — PRD §11 accessibility.",
        }),
        defineField({ name: "credit", title: "Photo credit", type: "string" }),
      ],
    }),
    defineField({
      group: "content",
      name: "body",
      title: "Body",
      type: "array",
      of: [{ type: "block" }],
      validation: (rule) => rule.required(),
    }),
    defineField({
      group: "content",
      name: "publishedAt",
      title: "Published at",
      type: "datetime",
      validation: (rule) => rule.required(),
    }),
    defineField({
      group: "content",
      name: "updatedAt",
      title: "Updated at",
      description: "Only set this when the story has been materially corrected or updated.",
      type: "datetime",
    }),
    defineField({
      group: "meta",
      name: "developing",
      title: "Developing / unconfirmed",
      description: 'Shows the "Developing" label — see design-decisions.md.',
      type: "boolean",
      initialValue: false,
    }),
    defineField({
      group: "meta",
      name: "sourceAttribution",
      title: "Source attribution",
      type: "string",
      validation: (rule) => rule.required(),
    }),
    defineField({
      group: "meta",
      name: "sourcesLog",
      title: "Sources & updates log",
      description: "Timestamped, visible corrections — never edit the body silently.",
      type: "array",
      of: [
        {
          type: "object",
          fields: [
            defineField({ name: "at", title: "When", type: "datetime", validation: (rule) => rule.required() }),
            defineField({ name: "note", title: "Note", type: "string", validation: (rule) => rule.required() }),
          ],
          preview: {
            select: { title: "note", subtitle: "at" },
          },
        },
      ],
    }),
    defineField({
      group: "meta",
      name: "relatedPosts",
      title: "Related posts",
      type: "array",
      of: [{ type: "reference", to: [{ type: "post" }] }],
      validation: (rule) => rule.max(4),
    }),
    defineField({
      group: "meta",
      name: "featured",
      title: "Featured (homepage lead story)",
      description: "Exactly one post should have this on at a time — it's the big homepage card.",
      type: "boolean",
      initialValue: false,
    }),
    defineField({
      group: "meta",
      name: "breaking",
      title: "Breaking (homepage strip)",
      description: "Exactly one post should have this on at a time — the thin urgent strip.",
      type: "boolean",
      initialValue: false,
    }),
    defineField({
      group: "meta",
      name: "spotlight",
      title: "Community spotlight",
      description: "Show in the homepage's Community spotlight row — pick up to 3 at a time.",
      type: "boolean",
      initialValue: false,
    }),
    defineField({
      group: "meta",
      name: "severity",
      title: "Travel severity",
      description: "Travel posts only — drives the status dot. Status is never colour alone.",
      type: "string",
      options: {
        list: [
          { title: "Severe (closed)", value: "severe" },
          { title: "Minor (delays)", value: "minor" },
          { title: "Clear", value: "clear" },
        ],
      },
      hidden: ({ document }) => document?.category === undefined,
    }),
    defineField({
      group: "seo",
      name: "metaTitle",
      title: "Meta title override",
      type: "string",
      description: "Leave blank to use the post title.",
    }),
    defineField({
      group: "seo",
      name: "metaDescription",
      title: "Meta description override",
      type: "text",
      rows: 2,
      description: "Leave blank to use the standfirst.",
    }),
  ],
  orderings: [
    {
      title: "Published, newest first",
      name: "publishedAtDesc",
      by: [{ field: "publishedAt", direction: "desc" }],
    },
  ],
  preview: {
    select: { title: "title", subtitle: "publishedAt", media: "featuredImage" },
  },
});
